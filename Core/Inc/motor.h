/* ============================================================================
 * motor.h —— 电机输出层对外接口
 * ==========================================================================*/
#ifndef _MOTOR_H
#define _MOTOR_H

#include "stm32f1xx_hal.h"

/* 直接驱动两个电机。范围 -7200 ~ 7200，符号决定转向，数值决定转速。
 * 内部自动做死区补偿（见 motor.c）。 */
void Load(int moto1,int moto2);

/* 把两个输出限制在合法范围内（原地修改） */
void Limit(int *motoA,int *motoB);

/* 摔倒保护检查。返回 1 表示已锁存，此时必须切断电机。
 * 参数为机械中心角与当前倾角。 */
uint8_t Stop(float *Med_Jiaodu,float *Jiaodu);

#endif
